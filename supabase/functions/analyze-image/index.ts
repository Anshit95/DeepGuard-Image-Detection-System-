
import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Max-Age": "86400",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  const jsonResponse = (body: unknown, status = 200) =>
    new Response(JSON.stringify(body), {
      status,
      headers: {
        ...corsHeaders,
        "Content-Type": "application/json",
      },
    });

  try {
    // 1. Receive image from frontend
    const { imageBase64, mimeType } = await req.json();

    if (!imageBase64 || !mimeType) {
      return jsonResponse(
        { error: "imageBase64 and mimeType are required" },
        400
      );
    }

    // 2. Validate image format
    const allowedTypes = [
      "image/jpeg",
      "image/png",
      "image/webp",
      "image/tiff",
    ];

    if (!allowedTypes.includes(mimeType)) {
      return jsonResponse(
        { error: "Unsupported image format" },
        400
      );
    }

    // 3. Get Gemini API key from Supabase Secrets
    const GEMINI_API_KEY = Deno.env.get("GEMINI_API_KEY");

    if (!GEMINI_API_KEY) {
      console.error("GEMINI_API_KEY is missing");
      return jsonResponse(
        { error: "Gemini API key is not configured in Supabase Secrets" },
        500
      );
    }

    // 4. Forensic analysis instructions
    const systemPrompt = `
You are an expert forensic image analyst.

Your task is to classify images into three categories:

1. REAL:
Authentic photographs captured using cameras or phones.

2. AI-GENERATED:
Images entirely generated by AI models such as
Stable Diffusion, Midjourney, DALL-E and Firefly.

3. MANIPULATED:
Real photographs that have been edited, composited,
spliced, retouched or modified.

FORENSIC INDICATORS:

REAL PHOTOGRAPHS:
- Natural camera sensor noise.
- Lens effects, chromatic aberration and vignetting.
- Consistent natural lighting and shadows.
- Natural JPEG compression artifacts.
- Skin pores, wrinkles and realistic skin texture.
- Natural motion blur and depth of field.
- Realistic perspective and background complexity.
- Genuine photographic imperfections.

AI-GENERATED IMAGES:
- Artificially smooth or plastic-looking skin.
- Impossible geometry or inconsistent anatomy.
- Unnatural reflections.
- Synthetic or repetitive textures.
- Garbled or distorted text.
- Inconsistent hair and fabric details.
- Unrealistic lighting and shadows.
- Background elements that dissolve into abstraction.

MANIPULATED IMAGES:
- Region-specific compression inconsistencies.
- Visible splicing or pasted-element boundaries.
- Inconsistent shadows and lighting.
- Repeated or cloned textures.
- Perspective and scale inconsistencies.
- Unnatural transitions between image regions.

IMPORTANT RULES:

- Never classify an image as AI-generated simply because
  it is blurry, compressed or low quality.
- WhatsApp and social-media compression are normal.
- Do not assume that every portrait or selfie is real.
- Do not assume that every polished image is AI-generated.
- Evaluate the actual visual evidence.
- Do not invent camera metadata or sensor measurements.
- If metadata is unavailable, do not claim that metadata
  has been independently verified.
- Visual inspection alone cannot establish authenticity
  with absolute certainty.

RETURN ONLY VALID JSON:

{
  "verdict": "real",
  "scores": {
    "real": 80,
    "aiGenerated": 10,
    "manipulated": 10
  },
  "signals": {
    "facialLandmarkConsistency": true,
    "frequencyArtifactScore": 2.0,
    "noisePatternResult": "Consistent",
    "metadataIntegrity": false,
    "compressionArtifacts": 2.0,
    "skinTextureNaturalness": 8.0,
    "eyeReflectionConsistency": true,
    "backgroundCoherence": 9.0
  },
  "explanation": "Provide 3-4 sentences explaining the visual evidence."
}

CLASSIFICATION REQUIREMENTS:

- Verdict must be real, ai_generated or manipulated.
- All three scores must be between 0 and 100.
- Scores must add up to exactly 100.
- Winning category should normally score between 55 and 95.
- Use realistic confidence estimates.
- Do not claim forensic certainty from visual analysis alone.
- All signal fields must follow the specified JSON types.
- Return JSON only, without Markdown or code fences.
`;

    // 5. Send image to Google Gemini API
    const response = await fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.8-flash:generateContent",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-goog-api-key": GEMINI_API_KEY,
        },
        body: JSON.stringify({
          systemInstruction: {
            parts: [
              {
                text: systemPrompt,
              },
            ],
          },

          contents: [
            {
              role: "user",
              parts: [
                {
                  text:
                    "Perform a forensic analysis of this image. " +
                    "Determine whether it is real, AI-generated or manipulated. " +
                    "Examine visual artifacts, lighting, textures, " +
                    "anatomy and background coherence. " +
                    "Return the result in the required JSON format.",
                },
                {
                  inlineData: {
                    mimeType: mimeType,
                    data: imageBase64,
                  },
                },
              ],
            },
          ],

          generationConfig: {
            temperature: 0.2,
            responseMimeType: "application/json",
          },
        }),
      }
    );

    // 6. Handle Gemini API errors
    if (!response.ok) {
      const errorText = await response.text();

      console.error(
        "Gemini API error:",
        response.status,
        errorText
      );

      if (response.status === 400) {
        return jsonResponse(
          { error: "Invalid Gemini request or image format." },
          400
        );
      }

      if (response.status === 401 || response.status === 403) {
        return jsonResponse(
          { error: "Gemini API key is invalid or does not have access." },
          502
        );
      }

      if (response.status === 429) {
        return jsonResponse(
          { error: "Gemini API rate limit exceeded. Try again later." },
          429
        );
      }

      return jsonResponse(
        { error: "Gemini AI analysis failed. Please try again." },
        502
      );
    }

    // 7. Extract Gemini response
    const data = await response.json();

    const content =
      data.candidates?.[0]?.content?.parts
        ?.map((part: { text?: string }) => part.text || "")
        .join("") || "";

    if (!content) {
      console.error(
        "Empty Gemini response:",
        JSON.stringify(data)
      );

      return jsonResponse(
        { error: "Gemini returned an empty analysis." },
        502
      );
    }

    // 8. Parse JSON response
    let jsonStr = content.trim();

    const jsonMatch = jsonStr.match(
      /```(?:json)?\s*([\s\S]*?)```/
    );

    if (jsonMatch) {
      jsonStr = jsonMatch[1].trim();
    }

    let analysis;

    try {
      analysis = JSON.parse(jsonStr);
    } catch (error) {
      console.error("JSON parsing failed:", error);
      console.error("Gemini content:", content);

      return jsonResponse(
        { error: "Failed to parse Gemini analysis results." },
        502
      );
    }

    // 9. Validate analysis response
    const validVerdicts = [
      "real",
      "ai_generated",
      "manipulated",
    ];

    if (
      !validVerdicts.includes(analysis.verdict) ||
      !analysis.scores ||
      !analysis.signals ||
      typeof analysis.explanation !== "string"
    ) {
      console.error("Invalid analysis structure:", analysis);

      return jsonResponse(
        { error: "Gemini returned an invalid analysis structure." },
        502
      );
    }

    const scores = [
      analysis.scores.real,
      analysis.scores.aiGenerated,
      analysis.scores.manipulated,
    ];

    if (
      scores.some(
        (score: number) =>
          typeof score !== "number" ||
          !Number.isFinite(score) ||
          score < 0 ||
          score > 100
      ) ||
      Math.round(scores.reduce(
        (sum: number, score: number) => sum + score,
        0
      )) !== 100
    ) {
      return jsonResponse(
        { error: "Gemini returned invalid confidence scores." },
        502
      );
    }

    // 10. Return analysis to DeepGuardAI frontend
    console.log(
      "Gemini image analysis completed:",
      analysis.verdict
    );

    return jsonResponse(analysis);

  } catch (error) {
    console.error("analyze-image error:", error);

    return jsonResponse(
      {
        error:
          error instanceof Error
            ? error.message
            : "Unknown server error",
      },
      500
    );
  }
});
